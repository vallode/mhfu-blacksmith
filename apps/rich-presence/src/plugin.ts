/**
 * The same presence as a PPSSPP Lua plugin (docs/lua-plugins.md in PPSSPP),
 * for builds that have them: PPSSPP runs it in the game and sends the
 * presence itself, so nothing else needs to run.
 *
 * Everything that comes from data/ is worked out here, with the companion's
 * own labels and pictures (presence.ts), and written into the script as
 * tables; the Lua only reads the game and picks from them.
 *
 *   pnpm --filter rich-presence plugin [--out <dir>]
 */
import { mkdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { areaNumber } from "blacksmith/src/lib/area-numbers.ts";
import {
  PRESENCE_HERB_ICON,
  presenceMonsterIcon,
  presenceWeaponIcon,
} from "blacksmith/src/lib/presence-icons";
import { FPS, QUEST_OFFSET, RELEASES, STAGE_OFFSET, TOWN_STAGES, WEAPON_OFFSET } from "./layout";
import { loadNames, type Catalog } from "./names";
import { SITE, TOWN_PLACES, WEAPON_CLASSES, placeLabel, starLabel } from "./presence";
import { mapTexture } from "./read";

export const PLUGIN_DIR = "mhfu-presence";
const GAME_IMAGE = `${SITE}/images/favicons/felyne-icon-512.png`;
const GAME_NAME = "Monster Hunter Freedom Unite";

/** A Lua string literal. */
export function luaString(text: string): string {
  let out = '"';
  for (const ch of text) {
    const code = ch.codePointAt(0)!;
    if (ch === "\\" || ch === '"') out += `\\${ch}`;
    else if (ch === "\n") out += "\\n";
    else if (code < 0x20 || code === 0x7f) out += `\\${String(code).padStart(3, "0")}`;
    else out += ch;
  }
  return out + '"';
}

const hex = (n: number) => `0x${n.toString(16).toUpperCase()}`;
const row = (key: number, values: (string | number)[]) =>
  `\t[${key}] = { ${values.map((v) => (typeof v === "number" ? String(v) : luaString(v))).join(", ")} },`;

export const PLUGIN_INI = `[options]
type = lua
name = Monster Hunter Freedom Unite presence
filename = presence.lua
version = 1

[games]
${Object.keys(RELEASES)
  .map((id) => `${id} = true`)
  .join("\n")}
`;

/** presence.lua, with the names and pictures of everything in `names`. */
export function buildScript(names: Catalog): string {
  const quests = names.ids.quests
    .sort((a, b) => a - b)
    .map((id) => `\t[${id}] = ${luaString(names.quest(id)!.title)},`);
  // Star labels need the quest file's stars, so the Lua makes them from the board (hub, rank).
  const boards = names.ids.quests
    .sort((a, b) => a - b)
    .map((id) => {
      const q = names.quest(id)!;
      return `\t[${id}] = ${luaString(`${q.hub}/${q.rank ?? ""}`)},`;
    });
  const starTables = new Set(
    names.ids.quests.map((id) => `${names.quest(id)!.hub}/${names.quest(id)!.rank ?? ""}`),
  );
  const stars = [...starTables].sort().map((board) => {
    const [hub, rank] = board.split("/");
    const labels = Array.from({ length: 12 }, (_, i) =>
      luaString(starLabel(hub!, rank || null, i + 1)),
    );
    return `\t[${luaString(board)}] = { ${labels.join(", ")} },`;
  });
  const monsters = names.ids.monsters
    .sort((a, b) => a - b)
    .flatMap((id) => {
      const m = names.monster(id);
      return m ? [row(id, [m.name, SITE + presenceMonsterIcon(m.slug)])] : [];
    });
  const weapons = { 5: [] as string[], 6: [] as string[] };
  for (const { table, id } of [...names.ids.weapons].sort((a, b) => a.id - b.id)) {
    const w = names.weapon(table, id);
    if (!w) continue;
    weapons[table].push(
      row(id, [
        SITE + presenceWeaponIcon(w.type, w.rarity),
        `${w.name} (${WEAPON_CLASSES[w.type] ?? w.type})`,
      ]),
    );
  }
  const maps = names.ids.maps
    .sort((a, b) => a - b)
    .flatMap((id) => {
      const name = placeLabel(names.map(id), null);
      if (!name) return [];
      // Area numbers by stage list place, 1-based in Lua.
      const areas = Array.from({ length: 32 }, (_, i) => areaNumber(mapTexture(id), i));
      return [`\t[${id}] = { name = ${luaString(name)}, areas = { ${areas.join(", ")} } },`];
    });
  const town = Object.entries(TOWN_STAGES).map(
    ([stage, place]) => `\t[${stage}] = ${luaString(TOWN_PLACES[place])},`,
  );
  const releases = Object.entries(RELEASES).map(
    ([id, r]) => `\t${id} = { hunter = ${hex(r.hunter)}, mapStages = ${hex(r.mapStages)} },`,
  );

  return `-- ${GAME_NAME} for Discord Rich Presence, from PPSSPP itself.
-- Generated by the MHFU repository's apps/rich-presence (src/plugin.ts) from its data/: don't edit.
-- The addresses and how they were found: docs/discord-rich-presence.md there.

local RELEASES = {
${releases.join("\n")}
}

local STAGE = ${STAGE_OFFSET}        -- u16, from the hunter's block
local QUEST = ${hex(QUEST_OFFSET)}  -- the quest object
local WEAPON = ${hex(WEAPON_OFFSET)}   -- the equipped weapon's box slot
local FPS = ${FPS}

local GAME_NAME = ${luaString(GAME_NAME)}
local GAME_IMAGE = ${luaString(GAME_IMAGE)}
local HERB_IMAGE = ${luaString(SITE + PRESENCE_HERB_ICON)}

-- By quest ID: its title
local QUESTS = {
${quests.join("\n")}
}
-- By quest ID: its board, which says how its star level reads
local QUEST_BOARDS = {
${boards.join("\n")}
}
-- By board: the label for each star level the quest file can hold
local STAR_LABELS = {
${stars.join("\n")}
}
-- By emID: { name, picture }
local MONSTERS = {
${monsters.join("\n")}
}
-- By equipment table (5 melee, 6 ranged) and ID: { picture, hover text }
local WEAPONS = {
\t[5] = {
${weapons[5].map((l) => "\t" + l).join("\n")}
\t},
\t[6] = {
${weapons[6].map((l) => "\t" + l).join("\n")}
\t},
}
-- By map ID: its name and the area number the map prints for each stage list place
local MAPS = {
${maps.join("\n")}
}
-- By stage, in town
local TOWN = {
${town.join("\n")}
}

${LOGIC}`;
}

/** The part of presence.lua that doesn't come from data/. */
const LOGIC = `local release = RELEASES[game.ID]
if release == nil then
\treturn
end
local block = release.hunter

local function inRam(address)
\treturn address ~= nil and address >= 0x08800000 and address < 0x0A000000
end

-- What a hunter's name is typed in: ASCII, kana and CJK punctuation, kanji, full-width forms.
local function nameUnit(u)
\treturn (u >= 0x20 and u <= 0x7E) or (u >= 0x3000 and u <= 0x30FF) or (u >= 0x4E00 and u <= 0x9FFF) or (u >= 0xFF01 and u <= 0xFF9F)
end

-- The loaded hunter's name (UTF-16, up to 9 characters, zero-padded), or nil before one is loaded.
local function hunterName()
\tif r8(block + 0x12) ~= 1 or (r8(block + 0x13) or 2) > 1 then
\t\treturn nil
\tend
\tlocal chars = {}
\tlocal ended = false
\tfor i = 0, 8 do
\t\tlocal u = r16(block + i * 2)
\t\tif u == nil then
\t\t\treturn nil
\t\telseif u == 0 then
\t\t\tended = true
\t\telseif ended or not nameUnit(u) then
\t\t\treturn nil
\t\telse
\t\t\tchars[#chars + 1] = utf8.char(u)
\t\tend
\tend
\tif #chars == 0 then
\t\treturn nil
\tend
\treturn table.concat(chars)
end

local function weapon()
\tif r8(block + WEAPON) ~= 1 then
\t\treturn nil
\tend
\tlocal byTable = WEAPONS[r8(block + WEAPON + 1)]
\treturn byTable and byTable[r16(block + WEAPON + 2)]
end

-- "Jungle area 5", "Snowy Mountains Base Camp", or the map's name.
local function place(map, stage)
\tlocal m = MAPS[map]
\tif m == nil then
\t\treturn GAME_NAME
\tend
\tlocal entry = release.mapStages + map * 8
\tlocal count, list = r32(entry), r32(entry + 4)
\tif count == nil or count > 32 or not inRam(list) then
\t\treturn m.name
\tend
\tfor i = 0, count - 1 do
\t\tif r16(list + i * 2) == stage then
\t\t\tlocal area = m.areas[i + 1] or i
\t\t\treturn area == 0 and (m.name .. " Base Camp") or (m.name .. " area " .. area)
\t\tend
\tend
\treturn m.name
end

-- The loaded quest's header, or nil in town.
local function quest()
\tlocal file = r32(block + QUEST + 0x4C)
\tif not inRam(file) or r32(file) ~= 0x4C or r32(file + 4) ~= 0x47444E32 then
\t\treturn nil
\tend
\tlocal delivery = (r32(file + 0x4C) & 0xFF) == 2
\treturn {
\t\tid = r16(file + 0x64),
\t\tstars = r8(file + 0x66),
\t\tmap = r8(file + 0x68),
\t\ttimeLimit = r32(file + 0x5C),
\t\ttarget = (not delivery and r16(file + 0x72) ~= 0) and r16(file + 0x70) or nil,
\t\tdelivery = delivery,
\t}
end

local function update()
\tlocal name = hunterName()
\tif name == nil then
\t\tpresence.set{ details = "In the menus", large_image = GAME_IMAGE, large_text = GAME_NAME }
\t\treturn
\tend
\tlocal w = weapon() or {}
\tlocal q = quest()
\tif q == nil then
\t\tpresence.set{
\t\t\tdetails = TOWN[r16(block + STAGE)] or "In town",
\t\t\tstate = name,
\t\t\tlarge_image = GAME_IMAGE,
\t\t\tlarge_text = GAME_NAME,
\t\t\tsmall_image = w[1],
\t\t\tsmall_text = w[2],
\t\t}
\t\treturn
\tend

\tlocal title = QUESTS[q.id] or ("Quest " .. q.id)
\tlocal labels = STAR_LABELS[QUEST_BOARDS[q.id] or ""]
\tlocal stars = labels and labels[q.stars] or ("★" .. q.stars)
\tlocal target = q.target and MONSTERS[q.target]
\tlocal image = target and target[2] or (q.delivery and HERB_IMAGE or GAME_IMAGE)
\tlocal timeLeft = r32(block + QUEST + 0x10) or q.timeLimit
\tpresence.set{
\t\tdetails = target and ("Hunting " .. target[1]) or title,
\t\tstate = place(q.map, r16(block + STAGE)),
\t\tlarge_image = image,
\t\tlarge_text = stars .. " · " .. title,
\t\tsmall_image = w[1],
\t\tsmall_text = w[2],
\t\telapsed = math.max(0, q.timeLimit - timeLeft) / FPS,
\t}
end

emu.every(60, update)
`;

function main(argv: string[]) {
  const i = argv.indexOf("--out");
  const out = path.resolve(i >= 0 && argv[i + 1] ? argv[i + 1]! : "dist");
  const dir = path.join(out, PLUGIN_DIR);
  mkdirSync(dir, { recursive: true });
  writeFileSync(path.join(dir, "plugin.ini"), PLUGIN_INI);
  writeFileSync(path.join(dir, "presence.lua"), buildScript(loadNames()));
  console.log(`Wrote ${dir}`);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) main(process.argv.slice(2));
