// Plain JavaScript, not next.config.ts, on purpose. Next compiles a .ts config
// and everything it imports, next-pwa included, down to ES5 with SWC, which
// turns next-pwa's async plugin functions (the offline fallback, the start-URL
// cache) into calls to helpers defined elsewhere in its module. next-pwa
// writes those functions into public/sw.js as source text, without the
// helpers, so the service worker threw "_async_to_generator is not defined"
// whenever a request failed, offline or not, instead of serving /offline/.
// A .mjs config is imported as is.
import withPWA, { runtimeCaching as defaultRuntimeCaching } from "@ducanh2912/next-pwa";
import fs from "fs";
import path from "path";
import { createHash } from "crypto";

// ---------------------------------------------------------------------------
// Build ID: fixed, changed by hand. Next writes the build ID into every
// exported page (two copies in its HTML, one in its RSC payload), so any ID
// that changes with the code (Next's random one, or a hash of src/) changes
// all ~11,000 page files on every deploy that touches src/, and Cloudflare
// uploads every one of them again. With a fixed ID a deploy uploads only the
// files whose content changed: a set-builder change is a handful of files.
//
// The cost: the client router compares this ID to tell an old tab from a new
// deploy, and reloads the page when they differ instead of loading the new
// deploy's chunks into the old page. With a fixed ID, a tab left open across
// a deploy keeps navigating client-side into the new pages. That's fine for
// most changes, since chunks are content-hashed and module IDs are stable.
// Bump BUILD_ID when a deploy must force open tabs to reload, e.g. a Next or
// React upgrade, or a change to the root layout or to shared client state.
// Bumping it re-uploads every page once.
// ---------------------------------------------------------------------------
const BUILD_ID = "2026-11-12";

/** @type {import("next").NextConfig} */
const nextConfig = {
  output: "export",
  trailingSlash: true,
  // The game data's loader (packages/game-data) is TypeScript source, and
  // imports its own modules as "./files.js", as Node's ESM resolution wants.
  // Webpack finds the .ts file behind each.
  transpilePackages: ["game-data"],
  webpack: (config) => {
    config.resolve.extensionAlias = { ...config.resolve.extensionAlias, ".js": [".ts", ".js"] };
    return config;
  },
  experimental: { viewTransition: true },
  generateBuildId: () => BUILD_ID,
  // Share links (/sets/<code>/<slug>/, SHARE_PATH in src/lib/set-link.ts) are
  // the set builder's page, served there by the Worker
  // (src/cloudflare/worker.ts). `next dev` has no Worker, so it does the same
  // here. An export can't rewrite, so only in development.
  ...(process.env.NODE_ENV === "development" && {
    rewrites: async () => [{ source: "/sets/:path*", destination: "/set-builder/" }],
  }),
};

// ---------------------------------------------------------------------------
// Offline precache entries (built at config load, i.e. during `next build`).
// Data bundles are read from public/data (generated by scripts/generate-data.ts,
// which runs first in the build script); images are globbed from public/images.
// Each entry's revision is a content hash so updates bust the cache cleanly.
// ---------------------------------------------------------------------------
/** @typedef {{ url: string, revision: string }} PrecacheEntry */

/** @param {string} p */
function hashFile(p) {
  return createHash("md5").update(fs.readFileSync(p)).digest("hex").slice(0, 16);
}

/** @returns {PrecacheEntry[]} */
function collectPrecacheEntries() {
  /** @type {PrecacheEntry[]} */
  const entries = [];
  const publicDir = path.join(process.cwd(), "public");

  // All data bundles (+ dictionaries + manifest) from public/data.
  const dataDir = path.join(publicDir, "data");
  if (fs.existsSync(dataDir)) {
    for (const f of fs.readdirSync(dataDir)) {
      if (!f.endsWith(".json")) continue;
      entries.push({ url: `/data/${f}`, revision: hashFile(path.join(dataDir, f)) });
    }
  }

  // Search index.
  const searchData = path.join(publicDir, "search-data.json");
  if (fs.existsSync(searchData)) {
    entries.push({ url: "/search-data.json", revision: hashFile(searchData) });
  }

  // Images the site uses (pixel-art sprites / icons), minus the ones it never
  // loads (scripts/lib/precache-exclude.json: unused weapon renders, README art).
  const imagesDir = path.join(publicDir, "images");
  /** @type {string[]} */
  const excluded = JSON.parse(
    fs.readFileSync(path.join(process.cwd(), "scripts", "lib", "precache-exclude.json"), "utf-8"),
  ).exclude;
  /** @param {string} relative */
  const isExcluded = (relative) =>
    excluded.some((e) => (e.endsWith("/") ? relative.startsWith(e) : relative === e));
  /** @param {string} dir */
  const walk = (dir) => {
    for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
      const full = path.join(dir, entry.name);
      const relative = path.relative(imagesDir, full).split(path.sep).join("/");
      if (entry.isDirectory()) {
        if (!isExcluded(`${relative}/`)) walk(full);
      } else if (/\.(png|jpg|jpeg|webp|gif)$/.test(entry.name) && !isExcluded(relative)) {
        entries.push({ url: `/images/${relative}`, revision: hashFile(full) });
      }
    }
  };
  if (fs.existsSync(imagesDir)) walk(imagesDir);

  return entries;
}

const additionalManifestEntries = collectPrecacheEntries();
// Version/cacheId from the data manifest hash so data updates invalidate cleanly.
let cacheId = "mhfu-blacksmith";
try {
  /** @type {{ version?: string }} */
  const manifest = JSON.parse(
    fs.readFileSync(path.join(process.cwd(), "public", "data", "data-manifest.json"), "utf-8"),
  );
  if (manifest.version) cacheId = `mhfu-${manifest.version}`;
} catch {
  // manifest not generated yet (e.g. plain `next build` without the pipeline)
}

export default withPWA({
  dest: "public",
  cacheOnFrontEndNav: true,
  aggressiveFrontEndNavCaching: true,
  reloadOnOnline: true,
  disable: process.env.NODE_ENV === "development",
  // When a navigation (full page load, or the hard-navigation Next.js falls
  // back to when a client-side RSC fetch fails offline) misses every cache,
  // serve this precached shell instead of a network error. It reads the
  // *actual* requested URL client-side and renders the right weapon/armor/
  // monster/decoration detail view from the already-cached data bundles —
  // see src/app/offline. This is what lets any of the ~3800 detail pages
  // work offline without precaching every single one of them.
  fallbacks: {
    document: "/offline/",
  },
  workboxOptions: {
    disableDevLogs: true,
    cacheId,
    // Precache all data bundles, images, and the app shell at SW install.
    additionalManifestEntries,
    runtimeCaching: [
      {
        // Data bundles: precached by workbox, but also serve the manual
        // offline cache the "Download for offline" button populates.
        urlPattern: /\/data\/.+\.json$/,
        handler: "CacheFirst",
        options: {
          cacheName: "mhfu-offline-v1",
        },
      },
      {
        // Search index
        urlPattern: /\/search-data\.json$/,
        handler: "CacheFirst",
        options: {
          cacheName: "mhfu-offline-v1",
        },
      },
      {
        // 3D models (public/models, see packages/mhfu-extract export-site): too
        // big to precache, so keep the ones a visitor has viewed.
        urlPattern: /\/models\/.+\.glb$/,
        handler: "CacheFirst",
        options: {
          cacheName: "models",
          expiration: { maxEntries: 200, maxAgeSeconds: 30 * 24 * 60 * 60 },
        },
      },
      {
        urlPattern: /\/models\/manifest\/.+\.json$/,
        handler: "NetworkFirst",
        options: {
          cacheName: "models",
        },
      },
      {
        // Cache images (pixel art sprites)
        urlPattern: /\/images\/.+\.(png|jpg|webp|gif)$/,
        handler: "CacheFirst",
        options: {
          cacheName: "images",
          expiration: { maxEntries: 1000, maxAgeSeconds: 30 * 24 * 60 * 60 },
        },
      },
      // Every weapon/armor/monster/decoration is its own statically-exported
      // route (~3800 of them) — App Router client navigation needs that
      // specific route's RSC payload (and the "pages" cache for a plain
      // document load/refresh) to exist offline, even though the visible
      // content is rendered from the already-cached compact JSON bundles
      // (src/lib/client-data.ts). We don't proactively download all ~3800
      // pages (see src/lib/offline-cache.ts) — instead, raise next-pwa's
      // default 32-entry cap on these three so pages you've actually
      // browsed (or that were auto-prefetched by <Link>) stay cached instead
      // of getting evicted almost immediately, which previously made
      // offline navigation to anything but the last few visited pages 404.
      {
        urlPattern: ({ request, url: { pathname }, sameOrigin }) =>
          request.headers.get("RSC") === "1" &&
          request.headers.get("Next-Router-Prefetch") === "1" &&
          sameOrigin &&
          !pathname.startsWith("/api/"),
        handler: "NetworkFirst",
        options: {
          cacheName: "pages-rsc-prefetch",
          expiration: { maxEntries: 4000, maxAgeSeconds: 86400 },
        },
      },
      {
        urlPattern: ({ request, url: { pathname }, sameOrigin }) =>
          request.headers.get("RSC") === "1" && sameOrigin && !pathname.startsWith("/api/"),
        handler: "NetworkFirst",
        options: {
          cacheName: "pages-rsc",
          expiration: { maxEntries: 4000, maxAgeSeconds: 86400 },
        },
      },
      {
        urlPattern: ({ url: { pathname }, sameOrigin }) =>
          sameOrigin && !pathname.startsWith("/api/"),
        handler: "NetworkFirst",
        options: {
          cacheName: "pages",
          expiration: { maxEntries: 4000, maxAgeSeconds: 86400 },
        },
      },
      // Supplying a custom `runtimeCaching` array replaces next-pwa's default
      // one entirely (it doesn't merge). Append the defaults after our own
      // rules above (data/image caches, and the higher-capacity page caches)
      // so those take precedence and only truly uncovered request types
      // (cross-origin assets, fonts, etc.) fall through to next-pwa's stock
      // behavior.
      ...defaultRuntimeCaching,
    ],
  },
})(nextConfig);
