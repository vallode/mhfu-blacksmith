/** Sharpness colours in order: red, orange, yellow, green, blue, white, purple. */
const SHARPNESS_EMOJI = ["🟥", "🟧", "🟨", "🟩", "🟦", "⬜", "🟪"];
/** The game's bar holds 45 points of sharpness; one emoji per 3 points fills 15. */
const SHARPNESS_CELLS = 15;
const SHARPNESS_PER_CELL = 3;

/**
 * Sharpness as a row of coloured squares, with ⬛ for the empty end of the
 * bar. Every colour the weapon has gets at least one square.
 */
export function sharpnessEmoji(values: (string | number)[]): string {
  let total = 0;
  let drawn = 0;
  let bar = "";
  values.forEach((v, i) => {
    const points = Number(v);
    if (!(points > 0)) return;
    total += points;
    const upTo = Math.max(drawn + 1, Math.round(total / SHARPNESS_PER_CELL));
    bar += SHARPNESS_EMOJI[i].repeat(upTo - drawn);
    drawn = upTo;
  });
  return bar + "⬛".repeat(Math.max(0, SHARPNESS_CELLS - drawn));
}

/** Title, description and the Open Graph / Twitter tags that repeat them. */
export function pageMetadata({
  title,
  description,
  path,
  image,
  oembed,
}: {
  /** The bare name, e.g. "Golden Serpentblade"; the site name is added to the tab title. */
  title: string;
  description: string;
  /** Route path, e.g. "/blacksmith/great-sword/". Resolved against metadataBase. */
  path: string;
  /** Thumbnail shown beside the embed text; defaults to the felyne. */
  image?: { url: string; width?: number; height?: number };
  /** Link the page's oEmbed file (see oembedPath), which adds the line above the title. */
  oembed?: boolean;
}): Metadata {
  const images = [image ?? DEFAULT_IMAGE];
  return {
    title: `${title} — ${SITE_NAME}`,
    description,
    alternates: {
      canonical: path,
      ...(oembed && { types: { "application/json+oembed": oembedPath(path) } }),
    },
    // A page-level openGraph replaces the layout's wholesale, so repeat the site fields.
    openGraph: {
      type: "website",
      siteName: SITE_NAME,
      locale: "en_US",
      url: path,
      title,
      description,
      images,
    },
    // "summary" shows the small icon beside the text, which suits these icon-sized images.
    twitter: { card: "summary", title, description, images },
  };
}

/** Embed accent: the item's rarity colour, else the site green. */
export function accentViewport(color?: string): Viewport {
  return { themeColor: color ?? THEME_COLOR };
}

const rarityPrefix = (rarity?: number | string | null) => (rarity ? `Rarity ${rarity} ` : "");

/** "Rarity 10 Long Sword", linking to the long sword tree. */
export const weaponAuthor = (w: Weapon): EmbedAuthor => ({
  name: `${rarityPrefix(w.rarity)}${titleCase(w.type)}`,
  path: `/blacksmith/${w.type}/`,
});

/** The stats under the title; the type and rarity are in the author line above it. */
export function weaponDescription(w: Weapon): string {
  const affinity = w.affinity && w.affinity !== "0%" ? w.affinity.replace(/^(\d)/, "+$1") : "";
  const stats = [
    w.attack ? `Attack ${w.attack}` : "",
    ...(w.elements ?? []).map((e) => `${element(e.name)} ${e.attack}`),
    affinity && `Affinity ${affinity.replace("-", "−")}`,
    `Slots ${slotGlyphs(w.slots)}`,
  ].filter(Boolean);

  return lines(
    stats.join(" · "),
    w.sharpness && `${sharpnessEmoji(w.sharpness)} Sharpness`,
    w.sharpness_plus && `${sharpnessEmoji(w.sharpness_plus)} Sharpness +1`,
  );
}

/** "Rarity 9 G-Rank Helmet · Gunner", linking to that slot and rank. */
export const armorAuthor = (p: ArmorPiece): EmbedAuthor => ({
  name: [
    `${rarityPrefix(p.rarity)}${rankLabel(p.rank)} ${titleCase(p.type)}`.trim(),
    p.hunter_type && p.hunter_type !== "Blademaster/Gunner" ? p.hunter_type : "",
  ]
    .filter(Boolean)
    .join(" · "),
  path: `/armorsmith/${p.type}/${p.rank}/`,
});

export function armorDescription(p: ArmorPiece): string {
  const stats = [
    p.defence !== undefined ? `Defense ${p.defence}` : "",
    `Slots ${slotGlyphs(p.slots)}`,
  ].filter(Boolean);

  const res = (
    [
      ["Fire", p.fire_res],
      ["Water", p.water_res],
      ["Thunder", p.thunder_res],
      ["Ice", p.ice_res],
      ["Dragon", p.dragon_res],
    ] as const
  )
    .filter(([, v]) => v !== undefined)
    .map(([n, v]) => `${ELEMENT_EMOJI[n]}${signed(v!)}`)
    .join(" ");

  return lines(
    stats.join(" · "),
    p.skills?.length &&
      `Skills: ${p.skills.map((s) => `${s.name} ${signed(s.amount)}`).join(", ")}`,
    res && `Resist ${res}`,
  );
}

/** "Flying Wyvern", linking to that category. */
export const monsterAuthor = (category: string): EmbedAuthor => ({
  name: titleCase(category),
  path: `/monsters/${category}/`,
});

export function monsterDescription(m: Monster): string {
  return (
    lines(m.description, m.habitats?.length && `Habitats: ${m.habitats.join(", ")}`) ||
    `${m.name} — ${titleCase(m.type)} in Monster Hunter Freedom Unite.`
  );
}

/** "Rarity 5 Decoration", linking to the decoration list. */
export const decorationAuthor = (d: Decoration): EmbedAuthor => ({
  name: `${rarityPrefix(d.rarity)}Decoration`,
  path: "/decorations/",
});

export function decorationDescription(d: Decoration): string {
  return lines(
    d.slots ? `Uses ${slotGlyphs(d.slots).replace(/—/g, "")}` : "",
    d.skills?.length && `Skills: ${d.skills.map((s) => s.replace(/ -(\d)/, " −$1")).join(", ")}`,
  );
}

export function itemDescription(name: string): string {
  return `Where to get ${name} in Monster Hunter Freedom Unite: the monster carves, breaks, captures and quest rewards that give it, best chance first.`;
}
