/** Tint names and colours: "plain" (untinted), "rarity-4"…"rarity-10", and the gem colours. */
export const EMBED_ICON_TINTS: Record<string, string | undefined> = {
  plain: undefined,
  ...Object.fromEntries(Object.entries(RARITY_COLORS).map(([r, c]) => [`rarity-${r}`, c])),
  ...GEM_COLORS,
};

/** The tinted 180px thumbnail for an icon: gem colour first, then rarity 4+, else plain. */
export function embedIcon(type: string, rarity?: number | null, gem?: string | null) {
  const tint =
    gem && GEM_COLORS[gem] ? gem : rarity && RARITY_COLORS[rarity] ? `rarity-${rarity}` : "plain";
  return { url: `/embed/icons/${type}-${tint}.png`, width: 180, height: 180 };
}

/** The colour the site's icons are tinted with: a gem colour, else rarity 4+; none below that. */
export function tintFor(rarity?: number | null, gem?: string | null): string | undefined {
  if (gem && GEM_COLORS[gem]) return GEM_COLORS[gem];
  if (rarity && RARITY_COLORS[rarity]) return RARITY_COLORS[rarity];
  return undefined;
}

export const rankLabel = (rank: string | undefined): string =>
  rank ? rankName(rank as GuildRank) : "";

export const signed = (n: number | string): string => {
  const v = Number(n);
  return v > 0 ? `+${v}` : `${v}`.replace("-", "−");
};

/** Newline-separated lines, skipping empty ones. */
export const lines = (...parts: (string | number | false | null | undefined)[]): string =>
  parts.filter((p) => p).join("\n");

/** Element and status icons; embeds show plain text, so these stand in for the game's. */
export const ELEMENT_EMOJI: Record<string, string> = {
  Fire: "🔥",
  Water: "💧",
  Thunder: "⚡",
  Ice: "❄️",
  Dragon: "🐉",
  Poison: "☠️",
  Paralysis: "💫",
  Sleep: "💤",
};

export const element = (name: string): string =>
  ELEMENT_EMOJI[name] ? `${ELEMENT_EMOJI[name]} ${name}` : name;

/** Slots as the game draws them: a circle per slot, dashes for the rest ("○○—"). */
export const slotGlyphs = (count = 0): string =>
  Array.from({ length: 3 }, (_, i) => (i < count ? "○" : "—")).join("");
