/**
 * Game-ID identity for `compare` and `build-data`.
 *
 * `extract` names every item from the vendored MHP2G enums, while the site
 * uses MHFU names. Matching the two sides by name misses every rename
 * ("Hornet Helm" vs "Hornetaur Helm"), so both commands match on the game's
 * own IDs instead:
 *
 * - **Disc side.** An extracted item's name is `enum[id]` for its slot's
 *   table (`strings/names.ts`), so the ID is recovered by looking the name
 *   back up. Every weapon, item and skill name in the enums is unique. The
 *   only duplicates are the Red/Blue Guild Guard armor pieces, which appear
 *   twice per slot; `extract` emits in ascending ID order, so the k-th
 *   occurrence of a name in its output is the k-th ID with that name.
 * - **Site side.** `data/equipment-ids.json` (generated by
 *   `scripts/generate-equipment-ids.ts`, which handles the MHP2G-vs-MHFU
 *   renames) maps each armor/weapon ID to the site item. Decorations and
 *   materials resolve through `data/items.json`'s `name`/`aliases`, with
 *   the same normalization as the site's own `src/lib/items.ts`.
 */
import { readFileSync } from "node:fs";
import path from "node:path";
import { isPlaceholderName, loadEnums } from "../strings/enums.js";
import type { NameTable } from "../strings/names.js";

/** Keys of `data/equipment-ids.json`. */
export type EquipmentSlot =
  "leggings" | "helmet" | "plate" | "gauntlets" | "waist" | "melee" | "ranged";

export interface EquipmentIdEntry {
  name: string;
  type?: string;
  sex?: string;
}

/** Real (non-placeholder) enum entries of `table`, name -> ascending IDs. */
function idsByName(table: NameTable): Map<string, number[]> {
  const entries = loadEnums().get(table);
  if (!entries) throw new Error(`ids: unknown enum table "${table}"`);
  const out = new Map<string, number[]>();
  entries.forEach((raw, id) => {
    if (isPlaceholderName(raw)) return;
    const name = raw.trim();
    out.set(name, [...(out.get(name) ?? []), id]);
  });
  return out;
}

/**
 * Recovers each extracted item's game ID from its enum name, in output
 * order. Returns `null` for a name that isn't in `table` (which would mean
 * the extract output came from a different enum version) or a duplicate
 * seen more often than the enum has it.
 */
export function assignDiscIds(names: string[], table: NameTable): (number | null)[] {
  const byName = idsByName(table);
  const seen = new Map<string, number>();
  return names.map((name) => {
    const ids = byName.get(name);
    if (!ids) return null;
    const nth = seen.get(name) ?? 0;
    seen.set(name, nth + 1);
    return ids[nth] ?? null;
  });
}

/** Game ID of a single, unique enum name (weapon upgrade-tree references). */
export function enumIdOf(name: string, table: NameTable): number | null {
  const ids = idsByName(table).get(name);
  return ids && ids.length === 1 ? ids[0]! : null;
}

let materialIds: Map<string, number[]> | null = null;

/**
 * `ItemID` of an extracted material name: `extract` emits `ItemID[id]` as
 * is, so this is the reverse lookup. A name two IDs share maps to `null`
 * (ambiguous) rather than guessing.
 */
export function discMaterialId(name: string): number | null {
  materialIds ??= idsByName("ItemID");
  const ids = materialIds.get(name);
  return ids && ids.length === 1 ? ids[0]! : null;
}

/** Same normalization as the site's `src/lib/items.ts` `normalizeItemName`. */
export function normalizeItemName(name: string): string {
  return name
    .replace(/\s+x\d+$/i, "")
    .replace(/\s+/g, " ")
    .trim()
    .toLowerCase();
}

/** Case-, space- and punctuation-insensitive key; keeps "+" ("Kut-Ku Scale" vs "Kut-Ku Scale+"). Same as `scripts/lib/mhp2g-enum.ts` `loose`. */
export function looseName(name: string): string {
  return name.toLowerCase().replace(/[^a-z0-9+]/g, "");
}

export interface ItemRecord {
  id: number;
  name: string;
  aliases?: string[];
}

/** Site-side lookups, loaded from a `data/` directory. */
export interface SiteIndex {
  /** `data/equipment-ids.json`: slot -> ID -> site item (null for IDs the site doesn't list). */
  equipment: Record<EquipmentSlot, (EquipmentIdEntry | null)[]>;
  /** `data/items.json` by ID. */
  items: Map<number, ItemRecord>;
  /** Item ID of a site material/decoration name (`name` or alias), or null if unknown/ambiguous. */
  itemIdOf(name: string): number | null;
  /** Game ID of a site armor/weapon, or null if `data/equipment-ids.json` doesn't list it. */
  equipmentIdOf(
    slot: EquipmentSlot,
    item: { name: string; type?: string; sex?: string },
  ): number | null;
  /** Every game ID in `slot` whose site name is `name` (any weapon type / sex). */
  equipmentIdsByName(slot: EquipmentSlot, name: string): number[];
}

/** Key used to find a site item's ID: weapons share an ID space per slot, so the weapon type disambiguates; Guild Guard pieces need `sex`. */
function equipmentKey(slot: EquipmentSlot, name: string, typeOrSex: string | undefined): string {
  return `${slot}\u0000${name}\u0000${typeOrSex ?? ""}`;
}

export function loadSiteIndex(dataDir: string): SiteIndex {
  const equipment = JSON.parse(
    readFileSync(path.join(dataDir, "equipment-ids.json"), "utf-8"),
  ) as SiteIndex["equipment"];
  const itemsFile = JSON.parse(readFileSync(path.join(dataDir, "items.json"), "utf-8")) as {
    items: ItemRecord[];
  };

  const items = new Map(itemsFile.items.map((i) => [i.id, i]));
  const owners = new Map<string, Set<number>>();
  const looseOwners = new Map<string, Set<number>>();
  for (const item of itemsFile.items) {
    for (const n of [item.name, ...(item.aliases ?? [])]) {
      const key = normalizeItemName(n);
      if (!key) continue;
      owners.set(key, (owners.get(key) ?? new Set()).add(item.id));
      looseOwners.set(looseName(n), (looseOwners.get(looseName(n)) ?? new Set()).add(item.id));
    }
  }

  const byKey = new Map<string, number>();
  const byName = new Map<string, number[]>();
  for (const [slot, entries] of Object.entries(equipment) as [
    EquipmentSlot,
    (EquipmentIdEntry | null)[],
  ][]) {
    entries.forEach((entry, id) => {
      if (!entry) return;
      const disambiguator = slot === "melee" || slot === "ranged" ? entry.type : entry.sex;
      byKey.set(equipmentKey(slot, entry.name, disambiguator), id);
      const nameKey = equipmentKey(slot, entry.name, undefined);
      byName.set(nameKey, [...(byName.get(nameKey) ?? []), id]);
    });
  }

  return {
    equipment,
    items,
    itemIdOf(name) {
      // Exact (site normalization) first, then ignoring spaces and
      // punctuation ("Constitutn Jewel" = "ConstitutnJewel").
      const ids = owners.get(normalizeItemName(name)) ?? looseOwners.get(looseName(name));
      return ids && ids.size === 1 ? [...ids][0]! : null;
    },
    equipmentIdOf(slot, item) {
      if (slot === "melee" || slot === "ranged")
        return byKey.get(equipmentKey(slot, item.name, item.type)) ?? null;
      // Only duplicated names carry `sex` in equipment-ids.json.
      return (
        byKey.get(equipmentKey(slot, item.name, item.sex)) ??
        byKey.get(equipmentKey(slot, item.name, undefined)) ??
        null
      );
    },
    equipmentIdsByName(slot, name) {
      return byName.get(equipmentKey(slot, name, undefined)) ?? [];
    },
  };
}
